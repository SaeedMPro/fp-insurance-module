def cover(doc):
    para(doc, "", space_after=30)
    para(doc, "دانشگاه بوعلی سینا", size=Pt(14), bold=True,
         align=WD_ALIGN_PARAGRAPH.CENTER, space_after=4, color=ACCENT)
    para(doc, "دانشکده فنی و مهندسی", size=Pt(12),
         align=WD_ALIGN_PARAGRAPH.CENTER, space_after=2, color=MUTED)
    para(doc, "گروه مهندسی کامپیوتر", size=Pt(12),
         align=WD_ALIGN_PARAGRAPH.CENTER, space_after=60, color=MUTED)

    para(doc, "تحلیل و طراحی پروژه ماژول بیمه تکمیلی", size=Pt(15),
         align=WD_ALIGN_PARAGRAPH.CENTER, space_after=18, color=MUTED)
    para(doc, "گزارش کار پروژه مهندسی", size=Pt(21), bold=True,
         align=WD_ALIGN_PARAGRAPH.CENTER, space_after=10, color=ACCENT)
    para(doc,
         "سامانه تحت وب مدیریت بیمه تکمیلی کارکنان با موتور قانون داده‌محور، "
         "گردش‌کار چندمرحله‌ای و ردیابی کامل",
         size=Pt(11.5), align=WD_ALIGN_PARAGRAPH.CENTER, space_after=90, color=MUTED)

    for label, value in [
        ("استاد راهنما", "جناب آقای دکتر مهدی سخایی‌نیا"),
        ("دانشجو", "سعید مظاهری"),
        ("شماره دانشجویی", "۴۰۲۴۲۹۹۰۰۴"),
        ("رشته و گرایش", "مهندسی کامپیوتر — نرم‌افزار"),
    ]:
        p = doc.add_paragraph()
        rtl_paragraph(p)
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_after = Pt(7)
        p.paragraph_format.line_spacing = 1.2
        set_run_font(p.add_run(f"{label}:  "), size=Pt(11), color=MUTED)
        set_run_font(p.add_run(value), size=Pt(12), bold=True)

    para(doc, "", space_after=60)
    para(doc, "مرداد ۱۴۰۵", size=Pt(11.5), align=WD_ALIGN_PARAGRAPH.CENTER, color=MUTED)


