    sec.bottom_margin = Cm(2.5)
    sec.left_margin = Cm(2.2)
    sec.right_margin = Cm(3.0)
    sectPr = sec._sectPr
    bidi = OxmlElement("w:bidi")
    sectPr.append(bidi)

